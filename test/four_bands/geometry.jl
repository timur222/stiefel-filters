@testset "Prescribed SC polygon and boundary faces" begin
    model = solve_polygon(3,1,2,.7,.2,.4)
    expected = [-1.,0.,.10524895188723614,.10771693489960055,.35160362376581167,
                .378265827765039,.9341606038809642,1.]
    @test model.geom.e ≈ expected atol=2e-9 rtol=0
    @test model.geom.slit ≈ [.2,.4] atol=2e-10
    @test model.diagnostics.max_height_error_tiles < 1e-7
    untrimmed = synthesize(model.endpoints,3;levels=(1,2))
    @test untrimmed.trims == (0.,0.)
    @test untrimmed.diagnostics.free_prevertex_count == 0
    single = solve_polygon(3,1,2,.7,.2,.4;trims=(0.,.3),sides=(:above,:below))
    recovered = synthesize(single.endpoints,3;levels=(1,2),sides=single.sides)
    @test recovered.trims[1]==0.
    @test recovered.trims[2] ≈ .3 atol=1e-7
    @test recovered.diagnostics.free_prevertex_count==1
    @test_throws ArgumentError solve_polygon(3,1,2,.7,.2,.4;trims=(.5,.5),sides=(:above,:below))
end

@testset "Automatic integer mode at degree 3000" begin
    # Input from reference results/prescribed-band-inverse.json, generated by
    # independent Python forward construction and trim inversion.
    E = [-1.,0.,.10524895188723614,.10771693489960055,
        .3516036261953735,.37826582131466446,.9341606038809642,1.]
    m = synthesize(E,3000)
    @test (m.m1,m.m2)==(1000,2000)
    @test m.sides==(:above,:below)
    @test m.T ≈ .0007 atol=1e-11
    @test maximum(abs.(collect(m.trims)-[.20000141076513955,.2999995412808403]))<5e-6
    @test m.diagnostics.max_height_error_tiles<1e-7
    @test m.diagnostics.candidate_count <= 196
end
